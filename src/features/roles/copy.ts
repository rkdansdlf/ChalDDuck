/**
 * 07 역할 조율이 **사용자에게 말하는 문구** 한 곳.
 *
 * ## 왜 코드 밖의 상수인가
 *
 * 역할 배정 규칙이 두 화면에서 **각각 다르게** 설명되고 있었다. 온보딩은
 * "고른 것·**경험**·**가능한 시간**" 이라고 했는데 코드에는 `경험` 이 없고, 가능한
 * 시간(`BusyBlock`)은 회의 계산 전용이라 역할 배정을 보면도 되지 않는다. 다른 화면은
 * "희망 역할과 추첨으로만" 이라고 했다 — **이게 맞다.**
 *
 * 틀린 쪽이 더 나쁜 이유는 둘이다.
 *
 * - **존재하지 않는 시스템을 안내한다.** "경험"을 입력할 곳이 없다. 사용자는 그 말을 믿고
 *   자기 경험을 넣었다고 생각한다.
 * - **같은 약속이 두 버전으로 산다.** 어느 쪽이 맞는지도 한 곳만 보면 알 수 없고, 다음에
 *   규칙을 고칠 때 어느 문구를 고쳐야 하는지도 답하기 어렵다.
 *
 * 그래서 규칙을 옆에 두지 않는다. 규칙은 `roster-model.ts` 에 있고 **말은 여기 한 곳에** 둔다.
 * 화면이 두 곳이면 말도 두 곳에 복사하지 않는다.
 */

/**
 * 역할이 **어떻게 정해지는지** — 사용자에게 보이는 설명.
 *
 * 규칙과 한 글자씩 맞춰 쓴다. 어느 문장이 어느 코드에 대응하는지는 각 주석에 적었다.
 * 규칙을 고칠 때 **문구도 여기서** 고친다.
 *
 * - `wantRole` — 희망을 기준으로 후보를 정한다(`candidatesFor`).
 * - `vetoRole` — **추첨 후보에서** 뺀다(`drawPoolOf`). 확정된 배정을 뒤집는 게 아니다.
 * - 희망자 1명 — `claimSoleRole`. 다른 사람이 대신 누를 수는 없다.
 * - 희망자 2명 이상 — `negotiating`. 이야기하거나 추첨한다.
 * - MBTI·가능한 시간 — 역할 배정에 **읽지 않는다.** `drawPoolOf` 에도, `drawForRole` 에도 없다.
 *
 * "혼자 희망하면 바로 맡고" 가 실제로는 **누가 누르느냐**의 문제인 점은 주석에만 적었다 —
 * `claimSoleRole` 은 그 사람이 눌러야 하지만, 사람이 다를 수는 없으므로 사실상 자동이다.
 * 화면에 그 조차를 쓰면 사용자는 자기 차례를 확인해야 하는 것 같아서 묻는다.
 */
