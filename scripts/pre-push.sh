#!/bin/sh
# 푸시 전에 `npm run verify` 를 돌린다 — Vercel 이 하는 배포 게이트를 **더 엄격하게** 로컬에서 한다.
#
# ## 왜 있는가
#
# 2026-09-28: 화면만 먼저 반영하고 `src/data/api.ts` 반영을 빼서 **타입 에러 57건**인 커밋이
# push 됐다. Vercel 빌드가 실패했고(2회), 그 사실을 알게 된 건 배포 목록을 봤을 때였다.
#
# 이 훅이 막는 것은 정확히 그 사건이다.
#
# ## Vercel 과 "같은 순서"가 아니라, 더 엄격하다
#
# 두 곳이 하는 일을 **같은 줄**로 적어 두면 어느 한쪽이 조용히 따로 놀게 된다. 그래서
# 공유하는 것과 다른 것을 나눈다.
#
# | | 로컬 (이 훅 · `npm run verify`) | Vercel (`vercel.json`) |
# |---|---|---|
# | `prisma migrate deploy` | — | **한다.** 운영 DB 에 실제로 적용한다 |
# | `db:check` · `storage:check:gate` · `build` | 한다 | 한다 |
# | `db:migrations` | **한다** | — |
# | `test` · `tsc` · `lint` | **한다** | — |
#
# 로컬에만 있는 세 개는 각자의 이유가 있다.
# - `db:migrations` — "마이그레이션 파일을 커밋했는가"다. Vercel clone 은 이미 커밋된 것만
#   받아서 **항상 통과한다.** 넣어 봐야 아무 정보도 없다.
# - `test` · `tsc` · `lint` — 시간을 산다. 배포를 막을 이유가 아니라면 CI 에서 돌린다.
#
# 반대로 Vercel 만 하는 `prisma migrate deploy` 는 로컬에서 대신할 수 없다 — 그게 바로
# 2026-09-28 실패한 배포의 순서였다. **빌드는 죽었는데 마이그레이션은 이미 운영 DB 에
# 적용된 상태**로 남는다. 그래서 배포는 빌드와 마이그레이션 사이에서 중간에 멈출 수 있고,
# 그때를 대비해 **롤백이 아니라 코드를 굴리는 쪽**(롤 포워드)을 택했다.
#
# `verify` 는 공통 게이트를, `verify:code` 는 코드 검사를 혼자 부른다 — 어디까지 돌렸는지
# 말할 수 있어야 어디서 실패했는지 안다.
#
# ## 이 훅이 지나는 커밋만이 배포된다
#
# **배포는 커밋을 푸시하는 것으로 한다.** `vercel --prod` 로 직접 올리지 않는다.
#
# 2026-09-30 에 이 규칙이 없었던 대가가 실제로 치렀다 — 더러운 워킹 트리를 CLI 로 올려서
# **커밋에 없는 코드가 프로덕션에서 돌았다.** 커밋되지 않은 마이그레이션이 있었다.
#
# 이 훅과 `db:migrations` 은 **모두 로컬 커밋과 로컬 DB 만 본다.** `vercel --prod` 는 그 둘을
# 보지 않고 디스크를 그대로 올리므로, 커밋하지 않은 마이그레이션이 **운영 DB 에** 적용될 수
# 있다. 그러면 배포는 조용히 성공하고 읽는 순간 `P2022` 로 죽는다.
#
# 즉 위 표의 모든 줄은 **push 경로에서만** 성립한다. 이 훅은 그 경로의 문지기고, 정문은
# `git push` 다. 규칙 전문은 [`CLAUDE.md`](../CLAUDE.md) 의 「배포는 커밋을 푸시하는 것으로
# 한다」 에 있다.
#
# ## 왜 저장소 안에 있는가
#
# `.git/hooks/` 는 커밋되지 않는다 — 여기 적어도 두면 아무도 모른다. 그래서 규칙은 이 파일에
# 두고, `.git/hooks/pre-push` 는 이 파일을 부르는 것만 한다.
#
# 다른 사람이 이 저장소를 쓰다면:
#
#     mkdir -p .git/hooks
#     cp scripts/pre-push.sh .git/hooks/pre-push && chmod +x .git/hooks/pre-push
#
# ## 검사를 빼고 싶은 경우
#
# `--no-verify` 로 부를 수 있다. 다만 Vercel 빌드가 빨개질 거라는 것을 알고 하자 — 오늘
# 그렇게 알 수 있었던 건 배포 목록을 봤을 때뿐이었다.

set -e

cd "$(git rev-parse --show-toplevel)"

echo ""
echo "── 푸시 전 검사 (npm run verify) ──────────────────────────"
echo "   깨진 커밋이 Vercel 빌드까지 가지 않도록 여기서 막습니다."
echo "   시간이 걸리면 --no-verify 로 부르되, 그 뒤 배포가 빨개질 수 있습니다."
echo ""

npm run verify

echo ""
echo "── 검사 통과. 푸시합니다. ──────────────────────────────────"
echo ""
