-- 구버전 서버를 위한 **다리**: `IceSeat.voteForId` 를 되살린다.
--
-- ## 왜 되살리나 (2026-09-30)
--
-- `20260930190000_ice_ballot` 가 이 컬럼을 지웠다. 그리고 `vercel.json` 은
-- `prisma migrate deploy` 를 **빌드 맨 앞**에서 돕니다. 그 사이 아직 구버전 인스턴스가 트래픽을
-- 받고 있는데, 구버전 `ice.ts` 는 이 컬럼을 읽고 쓴다.
--
-- ```
-- castIceVote() → UPDATE "IceSeat" SET "voteForId" = …   ← 컬럼이 없으면 P2022
-- closeIceVote() → SELECT … "voteForId"                   ← likewise
-- ```
--
-- 즉 배포 순간부터 빌드가 끝날 때까지, 진행 중인 판의 투표·밤 행동이 **전부 실패**한다. 데이터가
-- 깨지는 것은 아니고(옛 코드의 쓰기는 통째로 거절된다) 행동만 죽는다 — 그래도 사용자에게는
-- "처리하지 못했습니다" 로 보인다.
--
-- ⚠️ `npm run db:check` 는 이걸 막지 못한다. 이 시점엔 스키마와 DB 가 **둘 다 새 상태**라
--    일치하기 때문이다. 그 검사는 커밋 시점의 것일 뿐, **구버전 인스턴스와의 호환성은 보지 않는다.**
--
-- ## 이 다리는 언젠가 지운다
--
-- 새 코드는 표의 유일한 자리를 `IceBallot` 으로 삼고, 이 컬럼에는 **같이 써 줄 뿐** 읽지 않는다.
-- 그래서 구버전이 전부 사라진 다음 배포에서 이 컬럼을 다시 지우면 된다(그때는 아무도 안 쓰는
-- 컬럼이라 안전하다). 지우지 않으면 표의 자리가 두 벌이 되어, 어느 쪽이 진짜인지 알 수 없다.
--
-- ## 되돌리는 표
--
-- 진행 중인 판에 이미 던져진 표를 `IceBallot` 에서 되돌려 넣는다. 구버전 인스턴스가 이 판을
-- 마감하면 그 표로 세야 하는데, 되돌리지 않으면 **표가 0장으로 보이면서 마감**되고 아무도 탈락하지
-- 않는다. 끝난 판도 그대로 둔다 — 옛 코드는 결과를 공개할 때 마지막 표를 지우지 않았다.
-- ① 컬럼을 먼저 되살린다.
ALTER TABLE "IceSeat" ADD COLUMN IF NOT EXISTS "voteForId" TEXT;

-- ② 되돌리는 표
--
-- 진행 중인 판에 이미 던져진 표를 `IceBallot` 에서 되돌려 넣는다. 구버전 인스턴스가 이 판을
-- 마감하면 그 표로 세야 하는데, 되돌리지 않으면 **표가 0장으로 보이면서 마감**되고 아무도 탈락하지
-- 않는다. 끝난 판도 그대로 둔다 — 옛 코드는 결과를 공개할 때 마지막 표를 지우지 않았다.
INSERT INTO "IceSeat" ("roundId", "memberId", "voteForId")
SELECT b."roundId", b."memberId", b."targetId"
FROM "IceBallot" b
JOIN "IceRound" r ON r."id" = b."roundId"
-- 판의 마지막 투표 회차만 되돌린다 — 옛 코드가 보던 것은 "지금 고른 사람" 하나였다.
WHERE b."seq" = r."voteSeq"
ON CONFLICT DO NOTHING;
