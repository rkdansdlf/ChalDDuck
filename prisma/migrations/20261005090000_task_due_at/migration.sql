-- 업무 마감에 **기계가 비교할 수 있는 값**을 하나 둔다.

-- 왜: `Task.due` 는 자유 텍스트다. 실제로 "9/19", "9월쯤", "다음 주", "미정", "다음 발표까지" 가
-- 섞여 있어서 "마감이 가까운 업무가 몇 건이냐" 를 **셈으로 답할 수 없었다.** 홈 브리핑은 그래서
-- 그 자리를 "아직 안 정한 일" 로 대체했다 — 있는 숫자만 말하는 편이 나았다.
--
-- 이미 `SubmissionBox` 가 **같은 형태**로 `dueAt` + `due` 를 함께 들고 있다. 여기도 그 모양을
-- 맞춘다 — 한 화면이 마감 종류마다 다른 규칙을 쓰면 "제출함 마감은 세는데 업무 마감은 안 세어진다"
-- 가 조용히 벌어진다.

-- ⚠️ **기존 행은 채우지 않는다(`NULL` 로 둔다).** 2025년에 "9/19" 를 쓴 행이 2026년의 어느
-- 날인지 **누구도 모른다.** 추측해 채우면 그 값이 **근거 없는 사실**로 남고, 브리핑의
-- "마감 임박"이 그 추측 위에 선다. `NULL` 은 "모르겠다" 를 정직하게 말하는 값이다.
--
-- 앞으로 **새로 쓰거나 고치는 행만** 채운다(`lib/due.ts` 의 보수적 파싱 — 해석 못 하면 NULL).

-- AlterTable
ALTER TABLE "Task" ADD COLUMN "dueAt" TIMESTAMP(3);

-- 브리핑과 "마감 임박" 판정은 항상 (teamId, dueAt) 로 묶인다. NULL 이 많아도(B) 인덱스는
-- 팀 한 개의 마감만 훑으므로 크지 않다.
CREATE INDEX "Task_teamId_dueAt_idx" ON "Task"("teamId", "dueAt");
