-- 확정된 회의에 **날짜**를 붙인다.
--
-- 후보 행은 요일("수")로만 남으므로, 확정이 한 달을 넘겨 살아 있으면 화면 어디에도
-- "언제"가 없고 시간표 격자에도 그릴 칸을 찾지 못했다(후보 기간 7일이 지나면 요일이
-- 창 밖으로 나간다). 제안할 때 고른 날짜를 "MeetingProposal" 에 고정해 두면 확정된 회의가
-- "9/30(수) 16:00" 이라는 사실로 남는다.
--
-- NULL 허용으로 둔다 — 이미 올라온 제안의 날짜는 지금 돌아봐야 알 수 있고, 거짓말로 채우지
-- 않는다. NULL 인 행은 화면이 후보 기간 안의 요일로 되짚어 보여 준다(meeting-cell.ts).

ALTER TABLE "MeetingProposal" ADD COLUMN "date" TEXT;
