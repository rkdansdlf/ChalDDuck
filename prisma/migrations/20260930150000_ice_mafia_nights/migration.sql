-- 마피아 판에 **밤과 날짜**를 넣는다.
--
-- ## 무엇이 틀렸는가
--
-- 1) **밤이 없었다.** 마피아 판의 단계는 `play` 하나였고, 밤과 낮이 같은 단계였다. 그래서
--    밤이 언제 끝났는지 아무도 몰랐고, `markIceNightOut()` 을 두 번 누르면 **한 밤에 두 명이
--    죽었다.** 밤 행동은 말로 진행하지만, 밤에 빠지는 사람이 몇 명인지는 앱이 지켜야 한다 —
--    이것은 원래부터 앱 몫이었다.
--
-- 2) **투표가 언제 열렸는지 몰랐다.** 투표 버튼은 판을 여는 순간부터 켜져 있었다. 밤에 화면을
--    보다가 "투표 중" 을 보고 혼자 고른 표가 있었다.
--
-- ## 밤 → 토론 → 투표
--
-- 이제 마피아는 `night` → `discussion` → `voting` 을 돌고, 끝나면 `revealed` 다.
-- 동점이면 표를 지우고 `discussion` 으로 되돌아간다(다시 이야기하고 다시 투표한다).
-- 이길 때까지 `night` 로 돌아오며, 그때마다 `day` 가 하나씩 오른다.
--
-- ## 예전에 진행 중이던 판
--
-- ⚠️ **마이그레이션이 `play` 를 고치지 않는다.** 진행 중이던 마피아 판은 예전 그대로 두고 읽을
-- 때만 해석한다(`view.ts` 의 `icePhase`) — 예전 `play` 는 "투표가 열려 있는" 상태였으므로
-- `voting` 으로 읽는다. 값을 고치면 진행 중인 판이 갑자기 밤으로 넘어가 아무도 못 죽는다.
--
-- ## day 의 기본값
--
-- 1 이다. 라이어 판은 이 값을 쓰지 않는다 — 라이어에는 밤이 없다.
ALTER TABLE "IceRound" ADD COLUMN "day" INTEGER NOT NULL DEFAULT 1;
